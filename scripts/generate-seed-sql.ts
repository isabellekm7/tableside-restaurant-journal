/**
 * Generates supabase/seed.sql from the TypeScript sample data, so the database
 * and the app's bundled fallback data can never drift apart.
 *
 *   npm run db:seed-sql
 *
 * The output is idempotent (upserts): re-running it updates the catalog without
 * touching user data such as feedback or trip lists.
 */
import { writeFileSync } from 'node:fs'
import { ATTR_KEYS } from '../src/data/attributes'
import { CITIES, SEED_RESTAURANTS } from '../src/data/seed'
import type { DietaryTag } from '../src/data/types'

const q = (value: string): string => `'${value.replace(/'/g, "''")}'`
const json = (value: unknown): string => `${q(JSON.stringify(value))}::jsonb`
const textArray = (values: readonly string[]): string => (values.length === 0 ? "'{}'::text[]" : `array[${values.map(q).join(', ')}]`)

function upsert(table: string, columns: readonly string[], conflict: readonly string[], rows: readonly string[]): string {
  const updates = columns.filter((c) => !conflict.includes(c)).map((c) => `${c} = excluded.${c}`)
  return [
    `insert into public.${table} (${columns.join(', ')}) values`,
    rows.map((r) => `  (${r})`).join(',\n'),
    `on conflict (${conflict.join(', ')}) do update set ${updates.join(', ')};`,
  ].join('\n')
}

const cityRows = CITIES.map((c) =>
  [q(c.id), q(c.name), q(c.region), c.center.lat, c.center.lng, c.zoom, q(c.timeZone)].join(', '),
)

const restaurantColumns = [
  'id', 'city_id', 'name', 'cuisine', 'price_level', 'lat', 'lng', 'neighborhood', 'address_note', 'blurb',
  'hours', 'kid_windows', 'wait_profile', 'menu_highlights', 'watch_outs',
  'report_count', 'would_return_count', 'not_for_us_count', 'listing_kind', 'listing_partner', 'is_sample',
]
const restaurantRows = SEED_RESTAURANTS.map((r) =>
  [
    q(r.id), q(r.cityId), q(r.name), q(r.cuisine), r.priceLevel, r.location.lat, r.location.lng,
    q(r.neighborhood), q(r.addressNote), q(r.blurb),
    json(r.hours), json(r.kidWindows), json(r.waitProfile),
    textArray(r.menuHighlights), textArray(r.watchOuts),
    r.parentSignals.reportCount, r.parentSignals.wouldReturnCount, r.parentSignals.notForUsCount,
    r.listing ? q(r.listing.kind) : 'null', r.listing?.partner ? q(r.listing.partner) : 'null', 'true',
  ].join(', '),
)

const attributeRows = SEED_RESTAURANTS.flatMap((r) =>
  ATTR_KEYS.flatMap((key) => {
    const a = r.attributes[key]
    return a ? [[q(r.id), q(key), json(a.value), q(a.lastConfirmedAt), a.confirmationCount].join(', ')] : []
  }),
)

const dietaryRows = SEED_RESTAURANTS.flatMap((r) =>
  (Object.entries(r.dietary) as Array<[DietaryTag, { value: boolean; lastConfirmedAt: string; confirmationCount: number }]>).map(
    ([tag, a]) => [q(r.id), q(tag), a.value, q(a.lastConfirmedAt), a.confirmationCount].join(', '),
  ),
)

const sql = [
  '-- GENERATED by scripts/generate-seed-sql.ts from src/data/seed. Do not edit by hand.',
  '-- All restaurants are FICTIONAL sample data.',
  '',
  upsert('cities', ['id', 'name', 'region', 'center_lat', 'center_lng', 'zoom', 'time_zone'], ['id'], cityRows),
  '',
  upsert('restaurants', restaurantColumns, ['id'], restaurantRows),
  '',
  upsert('restaurant_attributes', ['restaurant_id', 'key', 'value', 'last_confirmed_at', 'confirmation_count'], ['restaurant_id', 'key'], attributeRows),
  '',
  upsert('restaurant_dietary', ['restaurant_id', 'tag', 'value', 'last_confirmed_at', 'confirmation_count'], ['restaurant_id', 'tag'], dietaryRows),
  '',
].join('\n')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`seed.sql: ${CITIES.length} cities, ${restaurantRows.length} restaurants, ${attributeRows.length} attributes, ${dietaryRows.length} dietary, ${sql.length} bytes`)
